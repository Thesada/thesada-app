package rulesgen

import (
	"fmt"
	"strings"
)

// Generate renders rules as the device's rules.lua. Deterministic: the same
// rules give the same bytes, so the saved sha256 shows drift.
// in: validated rules (from Parse). out: Lua source.
func Generate(rules []Rule) string {
	var b strings.Builder
	b.WriteString(header)
	byMetric := map[Metric][]int{}
	for i, r := range rules {
		byMetric[r.Metric] = append(byMetric[r.Metric], i)
	}
	if idx := byMetric[Temperature]; len(idx) > 0 {
		writeTemperature(&b, rules, idx)
	}
	if idx := byMetric[Current]; len(idx) > 0 {
		writeCurrent(&b, rules, idx)
	}
	if idx := byMetric[Battery]; len(idx) > 0 {
		writeBattery(&b, rules, idx)
	}
	return b.String()
}

const header = `-- rules.lua - generated by the thesada rules editor. Edits here are
-- overwritten on the next push, change the rules in the editor instead.

Log.info("rules.lua loaded")

local unit = Config.get("temperature.unit") or "C"

local sustain = {}
local sustain_start = {}
local cooldown = {}

-- True once key held for n readings or ms milliseconds, then starts over.
local function sustained(key, n, ms)
  local now = Node.uptime()
  sustain[key] = (sustain[key] or 0) + 1
  if not sustain_start[key] then
    sustain_start[key] = now
  end
  if sustain[key] >= n or (ms > 0 and now - sustain_start[key] >= ms) then
    sustain[key] = 0
    sustain_start[key] = nil
    return true
  end
  return false
end

local function clear(key)
  sustain[key] = 0
  sustain_start[key] = nil
end

local function can_alert(key, ms)
  local now = Node.uptime()
  return not (cooldown[key] and (now - cooldown[key]) < ms)
end

-- JSON string literal. String methods only, no table or math calls: older
-- firmware leaves those globals as plain strings.
local JSON_ESC = { ['"'] = '\\"', ['\\'] = '\\\\', ['\n'] = '\\n', ['\r'] = '\\r', ['\t'] = '\\t' }
local function json_str(v)
  local s = tostring(v):gsub('[%c"\\]', function(c)
    return JSON_ESC[c] or ("\\u%04x"):format(c:byte())
  end)
  return '"' .. s .. '"'
end

-- One alert per firing, code = the key's first part. Telegram.broadcast
-- publishes it and queues the chats, without the module the script publishes it.
local function notify(msg, key)
  Log.warn(msg)
  cooldown[key] = Node.uptime()
  local code = key:match("^[^:]+")
  if Telegram then
    Telegram.broadcast(msg, code)
  else
    MQTT.publish(Config.get("mqtt.topic_prefix") .. "/alert",
      '{"severity":"warn","code":' .. json_str(code) .. ',"message":' .. json_str(msg) .. '}')
  end
end
`

// ruleKey is the Lua expression for a rule's key: code, rule number, sensor.
func ruleKey(r Rule, n int, id string) string {
	k := LuaString(fmt.Sprintf("%s:%d", r.Code, n))
	if id == "" {
		return k
	}
	return k + ` .. ":" .. ` + id
}

func cmp(r Rule, expr string) string {
	if r.Above {
		return expr + " >= " + luaNumber(r.Value)
	}
	return expr + " <= " + luaNumber(r.Value)
}

func fire(b *strings.Builder, r Rule, indent, msg string) {
	ms := r.SustainMin * 60000
	fmt.Fprintf(b, "%sif sustained(key, %d, %d) and can_alert(key, %d) then\n", indent, r.SustainN, ms, r.CooldownMin*60000)
	fmt.Fprintf(b, "%s  notify(%s, key)\n", indent, msg)
	fmt.Fprintf(b, "%send\n", indent)
}

func nameMatch(r Rule, field string) string {
	if r.Sensor == "" {
		return ""
	}
	return field + " == " + LuaString(r.Sensor) + " and "
}

func writeTemperature(b *strings.Builder, rules []Rule, idx []int) {
	b.WriteString("\n-- Temperature. Thresholds are Celsius (temp_c), the message shows the\n-- configured unit. A probe without a reading arrives as stale.\n")
	b.WriteString("EventBus.subscribe(\"temperature\", function(data)\n")
	b.WriteString("  if not data.sensors then return end\n")
	b.WriteString("  for _, s in ipairs(data.sensors) do\n")
	b.WriteString("    local id = s.address or s.name\n")
	b.WriteString("    if s.stale then\n")
	for _, i := range idx {
		fmt.Fprintf(b, "      clear(%s)\n", ruleKey(rules[i], i+1, "id"))
	}
	b.WriteString("    else\n")
	for _, i := range idx {
		r := rules[i]
		fmt.Fprintf(b, "      do -- rule %d\n", i+1)
		fmt.Fprintf(b, "        local key = %s\n", ruleKey(r, i+1, "id"))
		fmt.Fprintf(b, "        if %s%s then\n", nameMatch(r, "s.name"), cmp(r, "s.temp_c"))
		fire(b, r, "          ", `s.name .. ": " .. (s.temp or s.temp_c) .. unit .. " - " .. `+LuaString(r.Msg))
		b.WriteString("        else\n          clear(key)\n        end\n      end\n")
	}
	b.WriteString("    end\n  end\nend)\n")
}

func writeCurrent(b *strings.Builder, rules []Rule, idx []int) {
	b.WriteString("\n-- Current channels.\n")
	b.WriteString("EventBus.subscribe(\"current\", function(data)\n")
	b.WriteString("  if not data.channels then return end\n")
	b.WriteString("  for _, ch in ipairs(data.channels) do\n")
	for _, i := range idx {
		r := rules[i]
		fmt.Fprintf(b, "    do -- rule %d\n", i+1)
		fmt.Fprintf(b, "      local key = %s\n", ruleKey(r, i+1, "ch.name"))
		fmt.Fprintf(b, "      if %s%s then\n", nameMatch(r, "ch.name"), cmp(r, "ch.current_a"))
		fire(b, r, "        ", `ch.name .. ": " .. ch.current_a .. "A - " .. `+LuaString(r.Msg))
		b.WriteString("      else\n        clear(key)\n      end\n    end\n")
	}
	b.WriteString("  end\nend)\n")
}

func writeBattery(b *strings.Builder, rules []Rule, idx []int) {
	b.WriteString("\n-- Battery.\n")
	b.WriteString("EventBus.subscribe(\"battery\", function(data)\n")
	b.WriteString("  if not data.present then return end\n")
	b.WriteString("  local pct = data.percent or -1\n")
	b.WriteString("  if pct < 0 then return end\n")
	for _, i := range idx {
		r := rules[i]
		fmt.Fprintf(b, "  do -- rule %d\n", i+1)
		fmt.Fprintf(b, "    local key = %s\n", ruleKey(r, i+1, ""))
		fmt.Fprintf(b, "    if %s then\n", cmp(r, "pct"))
		fire(b, r, "      ", `"Battery " .. pct .. "% - " .. `+LuaString(r.Msg))
		b.WriteString("    else\n      clear(key)\n    end\n  end\n")
	}
	b.WriteString("end)\n")
}
